; Zufall: 16-Bit-LFSR (Galois, Rueckkopplung 0xB400), A = Zufallsbyte, zerstoert HL
rnd:
        ld hl,(v_rng)
        srl h
        rr l
        jr nc,rn_1
        ld a,h
        xor 0xB4
        ld h,a
rn_1:   ld (v_rng),hl
        ld a,l
        xor h
        ret

; rnd_y: DE = Zeilenliste (16 Zellzeilen) -> A = Pixelzeile y; zerstoert HL
rnd_y:
        call rnd
        and 15
        ld l,a
        ld h,0
        add hl,de
        ld a,(hl)
        add a,a
        add a,a
        add a,a                 ; Zellzeile * 8
        ld l,a
        push hl
        call rnd
        pop hl
        and 7
        or l
        ret

