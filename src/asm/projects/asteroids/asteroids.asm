        jr print_str

; put_char: A = Zeichen (32-95), D = Zeile, E = Spalte
put_char:
        sub 32
        ld l,a
        ld h,0
        add hl,hl
        add hl,hl
        add hl,hl
        ld bc,font
        add hl,bc               ; HL = Glyphe
        ld a,d
        and 0x18
        ld b,a
        ld a,(v_draw)
        or b
        ld b,a                  ; B = Hi(Ziel)
        ld a,d
        and 7
        rrca
        rrca
        rrca
        or e
        ld c,a                  ; C = Lo(Ziel)
        ex de,hl                ; DE = Glyphe
        ld h,b
        ld l,c
        ld b,7                  ; nur 7 Zeilen: Zeile 8 bleibt frei (HUD-Trennlinie)
pc_l:   ld a,(de)
        ld (hl),a
        inc de
        inc h
        djnz pc_l
        ret

