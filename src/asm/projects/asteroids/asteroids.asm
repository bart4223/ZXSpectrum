        ld b,3
as_l:   ld (hl),e
        inc l
        ld (hl),c
        inc l
        ld (hl),c
        inc l
        ld (hl),c
        ld a,l
        add a,29
        ld l,a
        jr nc,as_2
        inc h
as_2:   djnz as_l
        ret

; old_ptr: HL = Zeiger auf alte Position des Zeichenpuffers
