; spr_ptr: A = Index (Bild*8+Verschiebung), HL = Tabelle -> DE = HL + Index*96
spr_ptr:
        push hl
        ld l,a
        ld h,0
        add hl,hl
        add hl,hl
        add hl,hl
        add hl,hl
        add hl,hl               ; *32
        ld d,h
        ld e,l
        add hl,hl               ; *64
        add hl,de               ; *96
        pop de
        add hl,de
        ex de,hl
        ret

; spr_geom: aus v_gx -> v_gcx, B = erste Byte-Spalte k0, C = Anzahl n (0 = ausserhalb), v_gc0, v_gskip
spr_geom:
        ld a,(v_gx)
        rrca
        rrca
        rrca
        and 0x1F
        ld c,a
        ld a,(v_gx+1)
        or a
        ld a,c
        jr z,sg_1
        add a,32
sg_1:   ld (v_gcx),a
        ld e,a
        ld b,0
        cp 2
        jr nc,sg_2
        ld a,2
        sub e
        ld b,a                  ; k0 = 2 - cx
sg_2:   ld a,e
        cp 32
        jr nc,sg_3
        ld a,2                  ; letzte Byte-Spalte
        jr sg_4
sg_3:   ld a,33
        sub e
        jr nc,sg_4
        ld c,0
        ret
sg_4:   sub b
        inc a
        ld c,a                  ; n
        add a,a
        ld d,a
        ld a,6
        sub d
        ld (v_gskip),a          ; 6 - 2*n (Start der naechsten Zeile + 2*k0)
        ld a,e
        sub 2
        add a,b
        ld (v_gc0),a
        ret

; spr16_draw: DE = Spritedaten (Bild/Verschiebung gewaehlt), v_gx/v_gy, v_gcol = Attribut
; setzt v_gn (0 = nichts gezeichnet)
spr16_draw:
        push de
        call spr_geom
        pop de
        ld a,c
        ld (v_gn),a
        or a
        ret z
        ld a,b                  ; Spritedaten ab Byte-Spalte k0
        add a,a
        add a,e
        ld e,a
        jr nc,sd_1
        inc d
sd_1:   ld a,(v_gc0)
        push bc
        ld c,a
        ld a,(v_gy)
        call row_addr           ; HL = Adresse der ersten Zeile
        pop bc
        ld a,(v_gn)
        cp 3
        jr z,sd_fast
        ld a,(v_grows)          ; allgemeiner Pfad (am Rand beschnitten): n Bytes je Zeile
        ld (v_gcnt),a
sd_row: ld b,c
sd_by:  ld a,(de)
        inc de
        and (hl)
        ld (hl),a
        ld a,(de)
        inc de
        or (hl)
        ld (hl),a
        inc l
        djnz sd_by
        ld a,l
        sub c
        ld l,a
        ld a,(v_gskip)
        add a,e
        ld e,a
        jr nc,sd_2
        inc d
sd_2:   down
        ld a,(v_gcnt)
        dec a
        ld (v_gcnt),a
        jr nz,sd_row
        jr sd_end
sd_fast:                        ; schneller Pfad: alle 3 Bytes sichtbar, Spritedaten per SP
        ex de,hl                ; HL = Spritedaten, DE = Bildschirm
        di
        ld (v_sp),sp
        ld sp,hl
        ex de,hl
        ld a,(v_grows)
        ld d,a
sd_fr:  pop bc
        ld a,(hl)
        and c
        or b
        ld (hl),a
        inc l
        pop bc
        ld a,(hl)
        and c
        or b
        ld (hl),a
        inc l
        pop bc
        ld a,(hl)
        and c
        or b
        ld (hl),a
        dec l
        dec l
        down
        dec d
        jp nz,sd_fr
        ld sp,(v_sp)
        ei
sd_end: ld a,(v_gcol)
        ld c,a
        jp spr16_attr

; spr16_erase: v_gx/v_gy -> Rechteck loeschen, Ebenenfarben wiederherstellen
spr16_erase:
        call spr_geom
        ld a,c
        or a
        ret z
        ld (v_gn),a
        push bc
        ld a,(v_gc0)
        ld c,a
        ld a,(v_gy)
        call row_addr
        pop bc
        ld a,(v_gn)
        cp 3
        jr z,sx_fast
        ld a,(v_grows)
        ld (v_gcnt),a
sx_row: ld b,c
        xor a
sx_by:  ld (hl),a
        inc l
        djnz sx_by
        ld a,l
        sub c
        ld l,a
        down
        ld a,(v_gcnt)
        dec a
        ld (v_gcnt),a
        jr nz,sx_row
        jr sx_end
sx_fast:
        ld a,(v_grows)
        ld d,a
        ld e,0
sx_f:   ld (hl),e
        inc l
        ld (hl),e
        inc l
        ld (hl),e
        dec l
        dec l
        down
        dec d
        jr nz,sx_f
sx_end: ld c,0
        jp spr16_attr

; spr16_attr: C = Farbe (0 = Ebenenfarbe wiederherstellen); Zellen ab v_gc0, v_gn breit
spr16_attr:
        ld a,(v_gc0)
        ld (v_xc),a
        ld a,(v_gy)
        rrca
        rrca
        rrca
        and 0x1F
        ld b,a
        ld a,(v_grows)
        dec a
        ld e,a
        ld a,(v_gy)
        add a,e
        rrca
        rrca
        rrca
        and 0x1F
        sub b
        inc a
        ld d,a                  ; 2 oder 3 Zellzeilen
        ld a,(v_gn)
        cp 3
        jr nz,sa_gen
        ld a,b
        call attr_row_addr      ; HL = erste Attributzelle
        ld a,c
        or a
        jr z,sa_rs
sa_s:   ld (hl),c               ; Farbe setzen (3 Zellen je Zeile)
        inc l
        ld (hl),c
        inc l
        ld (hl),c
        ld a,l
        add a,30
        ld l,a
        jr nc,sa_s2
        inc h
sa_s2:  dec d
        jr nz,sa_s
        ret
sa_rs:  ld e,b                  ; Ebenenfarbe je Zellzeile aus row_attr
        ld b,d
        ld d,ROWATTR_PG
sa_r:   ld a,(de)
        ld (hl),a
        inc l
        ld (hl),a
        inc l
        ld (hl),a
        inc e
        ld a,l
        add a,30
        ld l,a
        jr nc,sa_r2
        inc h
sa_r2:  djnz sa_r
        ret
sa_gen: ld a,b                  ; allgemeiner Pfad (1-2 Spalten am Rand)
sa_row: ld a,b
        call attr_row_addr
        ld a,(v_gn)
        ld e,a
        ld a,c
        or a
        jr nz,sa_f
        push hl
        ld l,b
        ld h,ROWATTR_PG
        ld a,(hl)
        pop hl
sa_f:   ld (hl),a
        inc l
        dec e
        jr nz,sa_f
        inc b
        dec d
        jr nz,sa_row
        ret

; erase_objs: alle Objekte dieses Puffers (Asteroiden + Explosionen) loeschen
