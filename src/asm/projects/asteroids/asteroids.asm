; spr_ptr: A = Index (Bild*8+Verschiebung), HL = Tabelle -> DE = HL + Index*96
spr_ptr:
        push hl
        ld l,a
        ld h,0
        add hl,hl
        add hl,hl
        add hl,hl
        add hl,hl
        add hl,hl               ; *32
        ld d,h
        ld e,l
        add hl,hl               ; *64
        add hl,de               ; *96
        pop de
        add hl,de
        ex de,hl
        ret

; spr_geom: aus v_gx -> v_gcx, B = erste Byte-Spalte k0, C = Anzahl n (0 = ausserhalb), v_gc0, v_gskip
spr_geom:
        ld a,(v_gx)
        rrca
        rrca
        rrca
        and 0x1F
        ld c,a
        ld a,(v_gx+1)
        or a
        ld a,c
        jr z,sg_1
        add a,32
sg_1:   ld (v_gcx),a
        ld e,a
        ld b,0
        cp 2
        jr nc,sg_2
        ld a,2
        sub e
        ld b,a                  ; k0 = 2 - cx
sg_2:   ld a,e
        cp 32
        jr nc,sg_3
        ld a,2                  ; letzte Byte-Spalte
        jr sg_4
sg_3:   ld a,33
        sub e
        jr nc,sg_4
        ld c,0
        ret
sg_4:   sub b
        inc a
        ld c,a                  ; n
        add a,a
        ld d,a
        ld a,6
        sub d
        ld (v_gskip),a          ; 6 - 2*n (Start der naechsten Zeile + 2*k0)
        ld a,e
        sub 2
        add a,b
        ld (v_gc0),a
        ret

; spr16_draw: DE = Spritedaten (Bild/Verschiebung gewaehlt), v_gx/v_gy, v_gcol = Attribut
; setzt v_gn (0 = nichts gezeichnet)
spr16_draw:
        push de
        call spr_geom
        pop de
        ld a,c
        ld (v_gn),a
        or a
        ret z
        ld a,b                  ; Spritedaten ab Byte-Spalte k0
        add a,a
        add a,e
        ld e,a
        jr nc,sd_1
        inc d
sd_1:   ld a,(v_gc0)
        push bc
        ld c,a
        ld a,(v_gy)
        call row_addr           ; HL = Adresse der ersten Zeile
        pop bc
        ld a,(v_gn)
        cp 3
        jr z,sd_fast
        ld a,16                 ; allgemeiner Pfad (am Rand beschnitten): n Bytes je Zeile
        ld (v_gcnt),a
sd_row: ld b,c
sd_by:  ld a,(de)
        inc de
        and (hl)
        ld (hl),a
        ld a,(de)
        inc de
        or (hl)
        ld (hl),a
        inc l
        djnz sd_by
        ld a,l
        sub c
        ld l,a
        ld a,(v_gskip)
        add a,e
        ld e,a
        jr nc,sd_2
        inc d
sd_2:   down
        ld a,(v_gcnt)
        dec a
        ld (v_gcnt),a
        jr nz,sd_row
        jr sd_end
sd_fast:                        ; schneller Pfad: alle 3 Bytes sichtbar, Spritedaten per SP
        ex de,hl                ; HL = Spritedaten, DE = Bildschirm
        di
        ld (v_sp),sp
        ld sp,hl
        ex de,hl
        ld d,16
