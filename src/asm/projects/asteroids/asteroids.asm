; hit_rocks: erster getroffener Asteroid -> A = 1, sonst A = 0
hit_rocks:
        ld ix,ASTS
        ld b,MAX_ROCKS
        ld de,ROCK_SZ
hr_l:   ld a,(ix+0)
        or a
        jr z,hr_n
        ld a,(ix+14)
        or a
        jr nz,hr_n              ; Kometen sind nicht abschiessbar
        ld a,(ix+15)            ; Treffer-Box nach Groesse (lh_tab: Abzug y, Hoehe y, Zugabe x, Breite x)
        add a,a
        add a,a
        ld hl,lh_tab
        add a,l
        ld l,a
        jr nc,hr_0
        inc h
hr_0:   ld a,(v_hy)             ; erst y pruefen (meist vorbei)
        sub (ix+5)
        sub (hl)
        inc hl
        cp (hl)
        jr nc,hr_n
        inc hl
        ld c,(hl)               ; Zugabe x
        inc hl
        ld l,(hl)               ; Breite x
        ld a,(v_hx)
        sub (ix+2)
        ld d,a
        ld a,(v_hx+1)
        sbc a,(ix+3)
        ld e,a
        ld a,d
        add a,c
        ld d,a
        ld a,e
        adc a,0
        jr nz,hr_n
        ld a,d
        cp l                    ; Gross: -5 <= dx <= 13
        jr nc,hr_n
        ld (ix+0),0             ; Treffer
        call spawn_expl
        call add_score
        call split_rock
        ld a,1
        ret
hr_n:   ld de,ROCK_SZ
        add ix,de
        djnz hr_l
        xor a
        ret

