; split_rock: Fels IX (gerade getroffen) zerfaellt in zwei kleinere (nur im Spiel, nicht gross -> klein ueber klein)
split_rock:
        ld a,SPLIT_ON
        or a
        ret z
        ld a,(v_mode)
        cp 1
        ret nz
        ld a,(ix+15)
        cp 2
        ret nc
        inc a
        ld (ix+15),a            ; Kind A = der Slot des Vaters
        ld (ix+0),1
        push ix
        ld ix,ASTS
        ld b,MAX_ROCKS
        ld de,ROCK_SZ
sp_f:   ld a,(ix+0)
        or a
        jr z,sp_got
        add ix,de
        djnz sp_f
        pop ix                  ; kein freier Slot: nur ein Kind
        jr sp_a
sp_got: push ix
        pop de                  ; DE = Platz fuer Kind B
        pop ix                  ; IX = Kind A
        push ix
        pop hl
        ld bc,ROCK_SZ
        ldir                    ; Kind B = Kopie von A
        push ix
        ld hl,-ROCK_SZ
        add hl,de
        push hl
        pop ix                  ; IX = Kind B
        ld a,(ix+8)
        sub 0x58
        ld (ix+8),a
        ld a,(ix+9)
        sbc a,0
        ld (ix+9),a
        ld a,(ix+6)
        sub 0x10
        ld (ix+6),a
        ld a,(ix+7)
        sbc a,0
        ld (ix+7),a
        ld a,(ix+13)
        xor 2                   ; B dreht gegenlaeufig
        ld (ix+13),a
        pop ix                  ; IX = Kind A
sp_a:   ld a,(ix+8)
        add a,0x58
        ld (ix+8),a
        ld a,(ix+9)
        adc a,0
        ld (ix+9),a
        ld a,(ix+6)
        add a,0x10
        ld (ix+6),a
        ld a,(ix+7)
        adc a,0
        ld (ix+7),a
        ret

