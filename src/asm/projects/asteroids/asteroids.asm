        xor a
sx_by:  ld (hl),a
        inc l
        djnz sx_by
        ld a,l
        sub c
        ld l,a
        down
        ld a,(v_gcnt)
        dec a
        ld (v_gcnt),a
        jr nz,sx_row
        jr sx_end
