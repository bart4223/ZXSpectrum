; scr_addr: B = y (0-191), C = x (0-255)  ->  HL = Pixeladresse
scr_addr:
        ld a,b
        and 7
        ld h,a
        ld a,b
        rra
        rra
        rra
        and 0x18
        or h
        ld h,a
        ld a,(v_draw)
        or h
        ld h,a
        ld a,b
        add a,a
        add a,a
        and 0xE0
        ld l,a
        ld a,c
        rrca
        rrca
        rrca
        and 0x1F
        or l
        ld l,a
        ret

; attr_addr: D = Zeile (0-23)  ->  HL = Attributadresse Spalte 0
