        ld a,(hl)
        and c
        or b
        ld (hl),a
        inc l
        pop bc
        ld a,(hl)
        and c
        or b
        ld (hl),a
        inc l
        pop bc
        ld a,(hl)
        and c
        or b
        ld (hl),a
        dec l
        dec l
        down
        dec d
        jp nz,sd_fr
        ld sp,(v_sp)
        ei
sd_end: ld a,(v_gcol)
        ld c,a
        jp spr16_attr

; spr16_erase: v_gx/v_gy -> Rechteck loeschen, Ebenenfarben wiederherstellen
spr16_erase:
        call spr_geom
        ld a,c
        or a
        ret z
        ld (v_gn),a
        push bc
        ld a,(v_gc0)
        ld c,a
        ld a,(v_gy)
        call row_addr
        pop bc
        ld a,(v_gn)
        cp 3
        jr z,sx_fast
        ld a,16
        ld (v_gcnt),a
