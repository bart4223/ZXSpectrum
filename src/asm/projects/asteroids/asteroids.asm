        ld a,(hl)
        ld (ix+8),a
        inc hl
        ld a,(hl)
        ld (ix+9),a
        ld a,c
        rlca
        rlca
        rlca
        and 1
        add a,a
        inc a                   ; Drehrichtung 1 oder 3 (= -1 mod 4)
        ld (ix+13),a
        call rnd
        ld c,a
        and 3
        add a,3
        ld (ix+12),a            ; Bilder pro Drehschritt 3..6
