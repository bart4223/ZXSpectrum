; flip: Anzeige umschalten, naechsten Zeichenpuffer bestimmen
flip:
        ld a,(v_disp)
        xor 0x08
        ld (v_disp),a
        ld bc,PORT_BANK
        out (c),a
        bit 3,a
        ld a,0x40               ; sichtbar Bank 7 -> zeichnen in Bank 5
        ld b,0
        jr nz,fl_1
        ld a,0xC0               ; sichtbar Bank 5 -> zeichnen in Bank 7
        ld b,1
fl_1:   ld (v_draw),a
        add a,0x18
        ld (v_attrhi),a
        ld a,b
        ld (v_buf),a
        add a,PG_HI0
        ld (v_hipg),a
        ret

; ---------------------------------------------------------------------
; frame_stats: Bilder seit dem letzten Durchlauf zaehlen
frame_stats:
        ld a,(FRAMES)
        ld b,a
        ld a,(v_lastf)
        ld c,a
        ld a,b
        ld (v_lastf),a
        sub c
        ld (v_dur),a
        ld hl,v_dshown
        cp (hl)
        jr z,fs_same
        ld (hl),a
        ld a,2
        ld (v_dyn),a            ; Anzeige in beiden Puffern neu zeichnen
fs_same:
        ld a,(v_started)
        or a
        jr nz,fs_go
        inc a
        ld (v_started),a        ; ersten Durchlauf nicht werten
        ret
fs_go:  ld a,(v_dur)
        ld hl,v_max
        cp (hl)
        ret c
        ld (hl),a
        ret

