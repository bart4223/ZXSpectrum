; ULAplus
ula_init:
        ld a,ULAPLUS_AUTO
        or a
        ret z                   ; Classic-only: ULAplus-Ports gar nicht anfassen
        ld a,ULA_DETECT
        or a
        jr nz,ui_detect
        ld a,1                  ; blind: Palette und Modus schreiben, ohne Ruecklesen
        ld (v_plus_av),a        ; (auf "The Spectrum" liefert das Ruecklesen nichts Brauchbares)
        call ula_palette
        ld a,ULA_START_ON
        ld (v_plus_on),a
        jp ula_set_mode
ui_detect:
        ld bc,0xBF3B
        ld a,0x40               ; Register 64 = Modus
        out (c),a
        ld b,0xFF               ; BC = 0xFF3B (Datenport)
        ld a,1
        out (c),a
        in a,(c)
        cp 1
        jr nz,ui_no
        xor a
        out (c),a
        in a,(c)
        or a
        jr nz,ui_no
        ld a,1
        ld (v_plus_av),a
        call ula_palette
        ld a,ULA_START_ON
        ld (v_plus_on),a
        jp ula_set_mode
ui_no:  ld a,0
        ld (v_plus_av),a
        ld (v_plus_on),a
        ret

; A = 1 an / 0 aus
ula_set_mode:
        push af
        ld bc,0xBF3B
        ld a,0x40
        out (c),a
        ld b,0xFF
        pop af
        out (c),a
        ret

; Palette: 4 CLUTs a 16 Eintraege (Tinte 0-7, Papier 8-15)
; Index = (Flash*2+Bright)*16 + (Tinte | Papier+8)
ula_palette:
        ld e,0
ulp_l:  ld a,e
        and 0x10                ; Bright-Bit des Index
        rrca                    ; -> 8
        ld d,a
        ld a,e
        and 7
        or d
        ld l,a
        ld h,0
        ld bc,pal_tab
        add hl,bc
        ld d,(hl)
        ld bc,0xBF3B
        out (c),e
        ld b,0xFF
        out (c),d
        inc e
        ld a,e
        cp 64
        jr nz,ulp_l
        ret

; Farben als GGGRRRBB: schwarz blau rot magenta gruen cyan gelb weiss
; normal: blau = ferne Sterne (dunkles Blaugrau), cyan = mittlere Sterne (Stahlblau)
; hell:   weiss = nahe Sterne und HUD
pal_tab:
        db 0x00,0x26,0x14,0x16,0xA0,0x8F,0xB4,0xB6      ; normal
        db 0x00,0x03,0x1C,0x1F,0xE0,0xE3,0xFC,0xFF      ; hell

