start:
        di
        ld sp,STACK_TOP
        im 1
        ld a,DISP_A
        ld bc,PORT_BANK
        out (c),a
        xor a
        out (0xFE),a            ; Rand schwarz

        ld hl,VARS              ; Variablen loeschen
        ld de,VARS+1
        ld bc,VARS_LEN-1
        ld (hl),0
        ldir
        ld a,DISP_A
        ld (v_disp),a
        ld hl,RNG_SEED
        ld (v_rng),hl
        ld a,2
        ld (v_dyn),a
        ld a,0xFF
        ld (v_dshown),a

        call ula_init           ; ULAplus-Palette setzen
        ld a,7
        ld e,0x3F               ; AY: alle Kanaele aus
        call ay_w
        ld a,8
        ld e,0
        call ay_w

        ld a,0x40
        call draw_static        ; statische Grafik in beide Puffer
        ld a,0xC0
        call draw_static        ; (laesst v_draw = 0xC0)
        ld a,0xD8
        ld (v_attrhi),a
        ld a,1
        ld (v_buf),a            ; sichtbar ist Bank 5, gezeichnet wird in Bank 7
        ld a,PG_HI0+1
        ld (v_hipg),a
        call stars_init
        ld hl,ASTS              ; Asteroiden, Explosionen, alte Slots loeschen
        ld de,ASTS+1
        ld bc,0xFF
        ld (hl),0
        ldir
        ld a,2
        ld (v_sdirty),a
        ld a,SHIP_X0
        ld (v_sx),a
        ld a,SHIP_Y0
        ld (v_sy),a
        ld hl,v_old             ; beide Puffer: Schiff zuletzt (nirgends) bei Start
        ld a,SHIP_X0/8
        ld (hl),a
        inc hl
        ld a,SHIP_Y0
        ld (hl),a
        inc hl
        ld a,SHIP_X0/8
        ld (hl),a
        inc hl
        ld a,SHIP_Y0
        ld (hl),a
        ei

