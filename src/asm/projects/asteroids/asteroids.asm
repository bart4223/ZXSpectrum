        ld de,rows_far
        ld b,STARS_FAR
        call si_layer
        ld de,rows_mid
        ld b,STARS_MID
        call si_layer
        ld de,rows_near
        ld b,STARS_NEAR
        call si_layer
        ld hl,SLOT0
        ld de,0x4000
        call si_slots
        ld hl,SLOT1
        ld de,0xC000
si_slots:
        ld b,NSTARS
sst_l:   ld (hl),e
        inc hl
        ld (hl),d
        inc hl
        ld (hl),0xFF
        inc hl
        ld (hl),0
        inc hl
        djnz sst_l
        ret

; si_layer: HL = Sternzeiger, DE = Zeilenliste, B = Anzahl
si_layer:
sl_l:   push bc
        push de
        push hl
        call rnd
        ld c,a                  ; C = x
        pop hl
        pop de
        push de
        push hl
        call rnd_y              ; A = y
        pop hl
        pop de
        ld (hl),0               ; Bruchteil
        inc hl
        ld (hl),c
        inc hl
        ld (hl),a
        inc hl
        pop bc
        djnz sl_l
        ret

; erase_stars: die Pixel loeschen, die in diesem Puffer zuletzt gesetzt wurden
; (Slots werden per SP gelesen: je Stern 4 Byte = Adresse, ~Maske, 0)
erase_stars:
        di
        ld (v_sp),sp
        ld a,(v_buf)
        or a
        ld sp,SLOT0
        jr z,es_go
        ld sp,SLOT1
es_go:  ld b,NSTARS
es_l:   pop hl
        pop de
        ld a,(hl)
        and e
        ld (hl),a
        djnz es_l
        ld sp,(v_sp)
        ei
        ret

; starpass: eine Ebene bewegen und zeichnen
;   slo/shi = Geschwindigkeit (8.8) nach links, endv = Low-Byte hinter dem letzten
;   Stern der Ebene, rows = Zeilenliste fuer das Wiederauftauchen
;   HL = Sternzeiger, IX = Slotzeiger (laufen weiter)
starpass macro slo,shi,endv,rows
        local lp,ok,dr
lp:     ld a,(hl)
        sub slo
        ld (hl),a
        inc hl
        ld a,(hl)
        sbc a,shi
        jr nc,ok
        ld (v_ssp),sp           ; links hinausgelaufen: rechts neu, neue Zeile
        ld sp,STACK_TOP-0x80    ; eigener kleiner Stack (der Rueckkehradresse nicht in die Quere kommen)
        push hl
        ld de,rows
        call rnd_y
        ld b,a
        pop hl
        ld sp,(v_ssp)
        ld a,255
        ld (hl),a
        ld c,a
        inc hl
        ld (hl),b
        jr dr
ok:     ld (hl),a
        ld c,a                  ; C = x
        inc hl
        ld b,(hl)               ; B = y
dr:     ld e,b
        ld d,PG_LO
        ld a,(de)               ; Adresse Lo der Pixelzeile
        ld b,a
        ld a,(v_hipg)
        ld d,a
        ld a,(de)               ; Adresse Hi (Puffer)
        ld d,a
        ld a,c
        rrca
        rrca
        rrca
        and 0x1F
        or b
        ld e,a                  ; DE = Pixeladresse
        ld a,c
        and 7
        or 0xC0
        ld c,a
        ld b,PG_LO
        ld a,(bc)               ; Maske
        ld c,a
        ld a,(de)
        or c
        ld (de),a               ; Pixel setzen
        ld a,c
        cpl
        ld c,a
        ld b,0
        push bc                 ; Slot: ~Maske, 0
        push de                 ;       Adresse (Slots rueckwaerts per SP geschrieben)
        inc hl                  ; naechster Stern
        ld a,l
        cp endv
        jp nz,lp
        endm

move_draw_stars:
        di
        ld (v_sp),sp
        ld a,(v_buf)
        or a
        ld sp,SLOT0+NSTARS*4
        jr z,md_go
        ld sp,SLOT1+NSTARS*4
md_go:  ld hl,STAR_BASE
        starpass 0x40,0,END_FAR,rows_far        ; fern: 0,25 Pixel/Bild
        starpass 0x80,0,END_MID,rows_mid        ; mittel: 0,5 Pixel/Bild
        starpass 0x00,1,END_NEAR,rows_near      ; nah: 1 Pixel/Bild
        ld sp,(v_sp)
        ei
        ret

; down_hl: eine Pixelzeile tiefer (Makro)
down    macro
        local dn1
        inc h
        ld a,h
        and 7
        jr nz,dn1
        ld a,l
        add a,32
        ld l,a
        jr c,dn1
        ld a,h
        sub 8
        ld h,a
dn1:
        endm

