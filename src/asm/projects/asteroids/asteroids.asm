; Raumschiff
; joy: Sinclair-Joystick 1 (Tasten 6 7 8 9 0 -> Port 0xEFFE, Bits 4..0 = links rechts runter hoch Feuer)
joy:
        ld a,(v_state)
        or a
        ret nz                  ; nur lebendes Schiff steuern
        ld a,(v_inp)
        ld c,a
        ld a,(v_sx)
        bit 4,c
        jr nz,jy_1
        sub SHIP_VX
        jr nc,jy_1
        xor a
jy_1:   bit 3,c
        jr nz,jy_2
        add a,SHIP_VX
        cp SHIP_XMAX+1
        jr c,jy_2
        ld a,SHIP_XMAX
jy_2:   ld (v_sx),a
        ld a,(v_sy)
        bit 1,c
        jr nz,jy_3
        sub SHIP_VY
        cp SHIP_YMIN
        jr nc,jy_3
        ld a,SHIP_YMIN
jy_3:   bit 2,c
        jr nz,jy_4
        add a,SHIP_VY
        cp SHIP_YMAX+1
        jr c,jy_4
        ld a,SHIP_YMAX
jy_4:   ld (v_sy),a
        ret

