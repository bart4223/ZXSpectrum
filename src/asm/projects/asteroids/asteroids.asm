        ld e,b
        ld d,ROWATTR_PG
        ld b,3
ar_l:   ld a,(de)
        ld (hl),a
        inc l
        ld (hl),a
        inc l
        ld (hl),a
        inc l
        ld (hl),a
        inc e
        ld a,l
        add a,29
        ld l,a
        jr nc,ar_2
        inc h
