; =====================================================================
; ASTEROIDS fuer ZX Spectrum 128K  -  Stufe 1: Parallax-Sternenhimmel
; Z80, pasmo (--tapbas), nur 128K.
;
; Stufe 0 (Geruest): 128K-Start, Doppelpuffer, ULAplus (blind), Layout, HUD
; Stufe 1 (neu):     Sternenhimmel mit 3 Ebenen, die nach links scrollen
;   - fern 0,5 / mittel 1 / nah 2 Pixel pro Bild (8.8-Festkomma)
;   - Farbe haengt an der Zellzeile: je Zeile eine feste Ebene (Tabelle row_attr)
;   - je Puffer eigene "alte Pixel"-Slots (Adresse + Maske), erst alle alten
;     Sterne loeschen, dann bewegen und neu setzen -> auch bei gleichem Byte korrekt
;   - Wiederauftauchen rechts mit zufaelliger Zeile aus der Zeilenliste der Ebene
;   - Zufall: 16-Bit-LFSR (feste Startzahl, Testlaeufe bleiben reproduzierbar)
;
; Speicher:  0x6000-0x7FFF reserviert (spaeter Sprites)
;            0x8000-...    Code und Daten, Tabellen auf Seitengrenzen
;            0xB400-0xB4FF Variablen (VARS)
;            0xB500-0xB5FF Sterne (3 Byte: Bruchteil, x, y)
;            0xB600/0xB700 alte Pixel je Puffer (3 Byte: Adresse, ~Maske)
;            0xBC00-0xBFFF Stack (waechst nach unten ab 0xC000)
;            0xC000-0xDAFF Bank 7 = Schattenbildschirm
; =====================================================================

ULAPLUS_AUTO equ 1              ; 1 = ULAplus nutzen, 0 = nie anfassen (nur Classic)
ULA_DETECT  equ 0               ; 1 = per Ruecklesen erkennen (geht auf "The Spectrum" nicht), 0 = blind schreiben
ULA_START_ON equ 1              ; 1 = ULAplus sofort an, 0 = Classic, Taste C schaltet ein
STARS_FAR   equ 24              ; Sterne je Ebene (mindestens 1 je Ebene, zusammen <= 85)
STARS_MID   equ 16
STARS_NEAR  equ 8
NSTARS      equ STARS_FAR+STARS_MID+STARS_NEAR

VARS        equ 0xB400
STAR_BASE   equ 0xB500
SLOT0       equ 0xB600
SLOT1       equ 0xB700
STACK_TOP   equ 0xC000
FRAMES      equ 0x5C78          ; Bildzaehler der ROM-Unterbrechung
PORT_BANK   equ 0x7FFD
DISP_A      equ 0x17            ; 48K-ROM, Bank 7 bei 0xC000, Bank 5 sichtbar
END_FAR     equ (STAR_BASE+3*STARS_FAR) and 255
END_MID     equ (STAR_BASE+3*(STARS_FAR+STARS_MID)) and 255
END_NEAR    equ (STAR_BASE+3*NSTARS) and 255
RNG_SEED    equ 0xACE1

; ---- Variablen -------------------------------------------------------
v_disp      equ VARS+0          ; aktueller Wert von Port 0x7FFD (sichtbar)
v_draw      equ VARS+1          ; Hi-Byte des Zeichenpuffers (0x40 oder 0xC0)
v_buf       equ VARS+2          ; Index des Zeichenpuffers (0 = Bank 5, 1 = Bank 7)
v_plus_av   equ VARS+3          ; ULAplus angenommen
v_plus_on   equ VARS+4          ; ULAplus eingeschaltet
v_ckey      equ VARS+5          ; Taste C war gedrueckt
v_lastf     equ VARS+6          ; letzter FRAMES-Wert (Low-Byte)
v_dur       equ VARS+7          ; Bilder des letzten Durchlaufs
v_max       equ VARS+8          ; Maximum seit Start (ohne ersten Durchlauf)
v_started   equ VARS+9
v_hipg      equ VARS+10         ; Seite der Hi-Tabelle des Zeichenpuffers
v_dyn       equ VARS+11         ; Dynamische Texte noch n Bilder zeichnen
v_dshown    equ VARS+12         ; zuletzt angezeigte Bilderzahl
v_rng       equ VARS+13         ; 16 Bit
v_sx        equ VARS+15         ; Schiff x (Pixel, 0..SHIP_XMAX)
v_sy        equ VARS+16         ; Schiff y (Pixel, SHIP_YMIN..SHIP_YMAX)
v_anim      equ VARS+17         ; Flammenzaehler 0..5
v_fl        equ VARS+18         ; Flammenbild 0..2
v_old       equ VARS+19         ; alte Schiffsposition je Puffer: xcell,y (2x2 Byte)
v_ty        equ VARS+23
v_xc        equ VARS+24
v_cnt       equ VARS+25
v_fdelay    equ VARS+26         ; Feuerpause (Bilder)
v_sfx       equ VARS+27         ; Pew: verbleibende Bilder
LASERS      equ VARS+0x20       ; 4 Strahlen x (aktiv, x, y, Alter)
v_lold      equ VARS+0x30       ; je Puffer 4 Strahlen x (gueltig, x, y-oben, Hoehe)
VARS_LEN    equ 0x50

LASER_MAX   equ 4
LASER_SPEED equ 4               ; Pixel/Bild
LASER_DELAY equ 7               ; Feuerpause: Schuss alle LASER_DELAY+1 Bilder
ATTR_LASER  equ 0x42            ; hell rot
ATTR_FLASH  equ 0x46            ; hell gelb (Muendungsblitz, erste 2 Bilder)
SFX_LEN     equ 8
SFX_V0      equ 8               ; Anfangslautstaerke (AY 0..15), Platzhalter bis Stufe 7

SHIP_VX     equ 3               ; Pixel/Bild waagerecht (ungerade = alle 8 Phasen)
SHIP_VY     equ 2               ; Pixel/Bild senkrecht
SHIP_XMAX   equ 224             ; 4 Zellen breit -> Zelle 28 ist die letzte Startzelle
SHIP_YMIN   equ 16
SHIP_YMAX   equ 175             ; 3 Zellzeilen -> bis Zeile 23
SHIP_X0     equ 40
SHIP_Y0     equ 88
ATTR_SHIP   equ 0x47            ; hell weiss
ATTR_FLAME  equ 0x46            ; hell gelb
ROWATTR_PG  equ row_attr/256
SHIP_PG     equ ship_tab/256

PG_LO       equ line_lo/256
PG_HI0      equ line_hi0/256

        org 0x8000

; =====================================================================
start:
        di
        ld sp,STACK_TOP
        im 1
        ld a,DISP_A
        ld bc,PORT_BANK
        out (c),a
        xor a
        out (0xFE),a            ; Rand schwarz

        ld hl,VARS              ; Variablen loeschen
        ld de,VARS+1
        ld bc,VARS_LEN-1
        ld (hl),0
        ldir
        ld a,DISP_A
        ld (v_disp),a
        ld hl,RNG_SEED
        ld (v_rng),hl
        ld a,2
        ld (v_dyn),a
        ld a,0xFF
        ld (v_dshown),a

        call ula_init           ; ULAplus-Palette setzen
        ld a,7
        ld e,0x3F               ; AY: alle Kanaele aus
        call ay_w
        ld a,8
        ld e,0
        call ay_w

        ld a,0x40
        call draw_static        ; statische Grafik in beide Puffer
        ld a,0xC0
        call draw_static        ; (laesst v_draw = 0xC0)
        ld a,1
        ld (v_buf),a            ; sichtbar ist Bank 5, gezeichnet wird in Bank 7
        ld a,PG_HI0+1
        ld (v_hipg),a
        call stars_init
        ld a,SHIP_X0
        ld (v_sx),a
        ld a,SHIP_Y0
        ld (v_sy),a
        ld hl,v_old             ; beide Puffer: Schiff zuletzt (nirgends) bei Start
        ld a,SHIP_X0/8
        ld (hl),a
        inc hl
        ld a,SHIP_Y0
        ld (hl),a
        inc hl
        ld a,SHIP_X0/8
        ld (hl),a
        inc hl
        ld a,SHIP_Y0
        ld (hl),a
        ei

main:
        call keys
        call joy
        call ship_anim
        call sfx_update
        call lasers_update
        call erase_stars
        call erase_ship
        call erase_lasers
        call move_draw_stars
        call draw_ship
        call draw_lasers        ; zuletzt: Strahlfarbe gewinnt ueber die Schiffszelle (gelber Muendungsblitz)
        call print_dyn
        halt                    ; auf Bildanfang warten
        call flip               ; fertig gezeichneten Puffer anzeigen
        call frame_stats
        jr main

; ---------------------------------------------------------------------
; flip: Anzeige umschalten, naechsten Zeichenpuffer bestimmen
flip:
        ld a,(v_disp)
        xor 0x08
        ld (v_disp),a
        ld bc,PORT_BANK
        out (c),a
        bit 3,a
        ld a,0x40               ; sichtbar Bank 7 -> zeichnen in Bank 5
        ld b,0
        jr nz,fl_1
        ld a,0xC0               ; sichtbar Bank 5 -> zeichnen in Bank 7
        ld b,1
fl_1:   ld (v_draw),a
        ld a,b
        ld (v_buf),a
        add a,PG_HI0
        ld (v_hipg),a
        ret

; ---------------------------------------------------------------------
; frame_stats: Bilder seit dem letzten Durchlauf zaehlen
frame_stats:
        ld a,(FRAMES)
        ld b,a
        ld a,(v_lastf)
        ld c,a
        ld a,b
        ld (v_lastf),a
        sub c
        ld (v_dur),a
        ld hl,v_dshown
        cp (hl)
        jr z,fs_same
        ld (hl),a
        ld a,2
        ld (v_dyn),a            ; Anzeige in beiden Puffern neu zeichnen
fs_same:
        ld a,(v_started)
        or a
        jr nz,fs_go
        inc a
        ld (v_started),a        ; ersten Durchlauf nicht werten
        ret
fs_go:  ld a,(v_dur)
        ld hl,v_max
        cp (hl)
        ret c
        ld (hl),a
        ret

; ---------------------------------------------------------------------
; keys: Taste C schaltet ULAplus um
keys:
        ld a,0xFE
        in a,(0xFE)             ; Port 0xFEFE: Shift Z X C V
        bit 3,a
        ld a,(v_ckey)
        jr z,ky_down
        xor a
        ld (v_ckey),a
        ret
ky_down:
        or a
        ret nz                  ; wird noch gehalten
        ld a,1
        ld (v_ckey),a
        ld a,(v_plus_av)
        or a
        ret z
        ld a,(v_plus_on)
        xor 1
        ld (v_plus_on),a
        ld a,2
        ld (v_dyn),a
        ld a,(v_plus_on)
        jp ula_set_mode

; ---------------------------------------------------------------------
; ULAplus
ula_init:
        ld a,ULAPLUS_AUTO
        or a
        ret z                   ; Classic-only: ULAplus-Ports gar nicht anfassen
        ld a,ULA_DETECT
        or a
        jr nz,ui_detect
        ld a,1                  ; blind: Palette und Modus schreiben, ohne Ruecklesen
        ld (v_plus_av),a        ; (auf "The Spectrum" liefert das Ruecklesen nichts Brauchbares)
        call ula_palette
        ld a,ULA_START_ON
        ld (v_plus_on),a
        jp ula_set_mode
ui_detect:
        ld bc,0xBF3B
        ld a,0x40               ; Register 64 = Modus
        out (c),a
        ld b,0xFF               ; BC = 0xFF3B (Datenport)
        ld a,1
        out (c),a
        in a,(c)
        cp 1
        jr nz,ui_no
        xor a
        out (c),a
        in a,(c)
        or a
        jr nz,ui_no
        ld a,1
        ld (v_plus_av),a
        call ula_palette
        ld a,ULA_START_ON
        ld (v_plus_on),a
        jp ula_set_mode
ui_no:  ld a,0
        ld (v_plus_av),a
        ld (v_plus_on),a
        ret

; A = 1 an / 0 aus
ula_set_mode:
        push af
        ld bc,0xBF3B
        ld a,0x40
        out (c),a
        ld b,0xFF
        pop af
        out (c),a
        ret

; Palette: 4 CLUTs a 16 Eintraege (Tinte 0-7, Papier 8-15)
; Index = (Flash*2+Bright)*16 + (Tinte | Papier+8)
ula_palette:
        ld e,0
ulp_l:  ld a,e
        and 0x10                ; Bright-Bit des Index
        rrca                    ; -> 8
        ld d,a
        ld a,e
        and 7
        or d
        ld l,a
        ld h,0
        ld bc,pal_tab
        add hl,bc
        ld d,(hl)
        ld bc,0xBF3B
        out (c),e
        ld b,0xFF
        out (c),d
        inc e
        ld a,e
        cp 64
        jr nz,ulp_l
        ret

; Farben als GGGRRRBB: schwarz blau rot magenta gruen cyan gelb weiss
; normal: blau = ferne Sterne (dunkles Blaugrau), cyan = mittlere Sterne (Stahlblau)
; hell:   weiss = nahe Sterne und HUD
pal_tab:
        db 0x00,0x26,0x14,0x16,0xA0,0x8F,0xB4,0xB6      ; normal
        db 0x00,0x03,0x1C,0x1F,0xE0,0xE3,0xFC,0xFF      ; hell

; ---------------------------------------------------------------------
; Zeichenhilfen (zeichnen immer in den Puffer v_draw)

; scr_addr: B = y (0-191), C = x (0-255)  ->  HL = Pixeladresse
scr_addr:
        ld a,b
        and 7
        ld h,a
        ld a,b
        rra
        rra
        rra
        and 0x18
        or h
        ld h,a
        ld a,(v_draw)
        or h
        ld h,a
        ld a,b
        add a,a
        add a,a
        and 0xE0
        ld l,a
        ld a,c
        rrca
        rrca
        rrca
        and 0x1F
        or l
        ld l,a
        ret

; attr_addr: D = Zeile (0-23)  ->  HL = Attributadresse Spalte 0
attr_addr:
        ld a,(v_draw)
        add a,0x18
        ld h,a
        ld a,d
        rrca
        rrca
        rrca
        ld l,a
        and 0x1F
        add a,h
        ld h,a
        ld a,l
        and 0xE0
        ld l,a
        ret

; fill_cells: HL = Adresse, B = Anzahl, A = Wert
fill_cells:
        ld (hl),a
        inc hl
        djnz fill_cells
        ret

; print_str: HL = Text (0-terminiert), D = Zeile, E = Spalte
print_str:
        ld a,(hl)
        or a
        ret z
        inc hl
        push hl
        push de
        call put_char
        pop de
        pop hl
        inc e
        jr print_str

; put_char: A = Zeichen (32-95), D = Zeile, E = Spalte
put_char:
        sub 32
        ld l,a
        ld h,0
        add hl,hl
        add hl,hl
        add hl,hl
        ld bc,font
        add hl,bc               ; HL = Glyphe
        ld a,d
        and 0x18
        ld b,a
        ld a,(v_draw)
        or b
        ld b,a                  ; B = Hi(Ziel)
        ld a,d
        and 7
        rrca
        rrca
        rrca
        or e
        ld c,a                  ; C = Lo(Ziel)
        ex de,hl                ; DE = Glyphe
        ld h,b
        ld l,c
        ld b,7                  ; nur 7 Zeilen: Zeile 8 bleibt frei (HUD-Trennlinie)
pc_l:   ld a,(de)
        ld (hl),a
        inc de
        inc h
        djnz pc_l
        ret

; ---------------------------------------------------------------------
; draw_static: A = Hi-Byte des Puffers (0x40 / 0xC0)
draw_static:
        ld (v_draw),a
        ld h,a
        ld l,0
        ld d,h
        ld e,1
        ld bc,6143
        ld (hl),l               ; 0
        ldir                    ; Pixel loeschen
        ld a,(v_draw)
        add a,0x18
        ld h,a
        ld l,0
        ld d,h
        ld e,1
        ld bc,767
        ld (hl),0x07
        ldir                    ; Attribute: weiss auf schwarz

        ld c,0                  ; Attribut je Zellzeile (HUD und Sternebenen)
ds_rows:
        ld d,c
        call attr_addr
        push hl
        ld hl,row_attr
        ld b,0
        add hl,bc
        ld a,(hl)
        pop hl
        ld b,32
        call fill_cells
        inc c
        ld a,c
        cp 24
        jr nz,ds_rows

        ld b,15                 ; Trennlinie unter dem HUD
        ld c,0
        call scr_addr
        ld b,32
sp_l:   ld (hl),0xFF
        inc l
        djnz sp_l

        ld hl,txt_p0
        ld de,0x0000
        call print_str
        ld hl,txt_p1
        ld de,0x0100
        jp print_str

txt_p0:  db "PUNKTE 000000  REKORD 000000",0
txt_p1:  db "LEVEL 01     LEBEN 3",0
txt_plus: db "PLUS",0
txt_std: db "STD ",0
txt_f:   db "F"
txt_fd:  db "1",0

; print_dyn: Dynamisches, jeweils 2 Bilder lang (so landet es in beiden Puffern)
print_dyn:
        ld a,(v_dyn)
        or a
        ret z
        dec a
        ld (v_dyn),a
        ld hl,txt_std
        ld a,(v_plus_on)
        or a
        jr z,pd_1
        ld hl,txt_plus
pd_1:   ld de,0x011C            ; Zeile 1, Spalte 28
        call print_str
        ld a,(v_dur)
        cp 10
        jr c,pd_2
        ld a,9
pd_2:   add a,'0'
        ld (txt_fd),a
        ld hl,txt_f
        ld de,0x001E            ; Zeile 0, Spalte 30: "F1" = Bilder pro Durchlauf
        jp print_str

; ---------------------------------------------------------------------
; Zufall: 16-Bit-LFSR (Galois, Rueckkopplung 0xB400), A = Zufallsbyte, zerstoert HL
rnd:
        ld hl,(v_rng)
        srl h
        rr l
        jr nc,rn_1
        ld a,h
        xor 0xB4
        ld h,a
rn_1:   ld (v_rng),hl
        ld a,l
        xor h
        ret

; rnd_y: DE = Zeilenliste (16 Zellzeilen) -> A = Pixelzeile y; zerstoert HL
rnd_y:
        call rnd
        and 15
        ld l,a
        ld h,0
        add hl,de
        ld a,(hl)
        add a,a
        add a,a
        add a,a                 ; Zellzeile * 8
        ld l,a
        push hl
        call rnd
        pop hl
        and 7
        or l
        ret

; ---------------------------------------------------------------------
; Sterne
; stars_init: Anfangsverteilung, alte-Pixel-Slots mit "nichts loeschen" fuellen
stars_init:
        ld hl,STAR_BASE
        ld de,rows_far
        ld b,STARS_FAR
        call si_layer
        ld de,rows_mid
        ld b,STARS_MID
        call si_layer
        ld de,rows_near
        ld b,STARS_NEAR
        call si_layer
        ld hl,SLOT0
        ld de,0x4000
        call si_slots
        ld hl,SLOT1
        ld de,0xC000
si_slots:
        ld b,NSTARS
ss_l:   ld (hl),e
        inc hl
        ld (hl),d
        inc hl
        ld (hl),0xFF
        inc hl
        djnz ss_l
        ret

; si_layer: HL = Sternzeiger, DE = Zeilenliste, B = Anzahl
si_layer:
sl_l:   push bc
        push de
        push hl
        call rnd
        ld c,a                  ; C = x
        pop hl
        pop de
        push de
        push hl
        call rnd_y              ; A = y
        pop hl
        pop de
        ld (hl),0               ; Bruchteil
        inc hl
        ld (hl),c
        inc hl
        ld (hl),a
        inc hl
        pop bc
        djnz sl_l
        ret

; erase_stars: die Pixel loeschen, die in diesem Puffer zuletzt gesetzt wurden
erase_stars:
        ld a,(v_buf)
        or a
        ld ix,SLOT0
        jr z,es_go
        ld ix,SLOT1
es_go:  ld b,NSTARS
        ld de,3
es_l:   ld l,(ix+0)
        ld h,(ix+1)
        ld a,(hl)
        and (ix+2)
        ld (hl),a
        add ix,de
        djnz es_l
        ret

; starpass: eine Ebene bewegen und zeichnen
;   slo/shi = Geschwindigkeit (8.8) nach links, endv = Low-Byte hinter dem letzten
;   Stern der Ebene, rows = Zeilenliste fuer das Wiederauftauchen
;   HL = Sternzeiger, IX = Slotzeiger (laufen weiter)
starpass macro slo,shi,endv,rows
        local lp,ok,dr
lp:     ld a,(hl)
        sub slo
        ld (hl),a
        inc hl
        ld a,(hl)
        sbc a,shi
        jr nc,ok
        push hl                 ; links hinausgelaufen: rechts neu, neue Zeile
        ld de,rows
        call rnd_y
        ld b,a
        pop hl
        ld a,255
        ld (hl),a
        ld c,a
        inc hl
        ld (hl),b
        jr dr
ok:     ld (hl),a
        ld c,a                  ; C = x
        inc hl
        ld b,(hl)               ; B = y
dr:     ld e,b
        ld d,PG_LO
        ld a,(de)               ; Adresse Lo der Pixelzeile
        ld b,a
        ld a,(v_hipg)
        ld d,a
        ld a,(de)               ; Adresse Hi (Puffer)
        ld d,a
        ld a,c
        rrca
        rrca
        rrca
        and 0x1F
        or b
        ld e,a                  ; DE = Pixeladresse
        ld a,c
        and 7
        or 0xC0
        ld c,a
        ld b,PG_LO
        ld a,(bc)               ; Maske
        ld c,a
        ld a,(de)
        or c
        ld (de),a               ; Pixel setzen
        ld a,c
        cpl
        ld (ix+2),a             ; Slot: Adresse und ~Maske merken
        ld (ix+0),e
        ld (ix+1),d
        ld bc,3
        add ix,bc
        inc hl                  ; naechster Stern
        ld a,l
        cp endv
        jp nz,lp
        endm

move_draw_stars:
        ld a,(v_buf)
        or a
        ld ix,SLOT0
        jr z,md_go
        ld ix,SLOT1
md_go:  ld hl,STAR_BASE
        starpass 0x40,0,END_FAR,rows_far        ; fern: 0,25 Pixel/Bild
        starpass 0x80,0,END_MID,rows_mid        ; mittel: 0,5 Pixel/Bild
        starpass 0x00,1,END_NEAR,rows_near      ; nah: 1 Pixel/Bild
        ret

; ---------------------------------------------------------------------
; Raumschiff
; joy: Sinclair-Joystick 1 (Tasten 6 7 8 9 0 -> Port 0xEFFE, Bits 4..0 = links rechts runter hoch Feuer)
joy:
        ld a,0xEF
        in a,(0xFE)
        ld c,a
        ld a,(v_sx)
        bit 4,c
        jr nz,jy_1
        sub SHIP_VX
        jr nc,jy_1
        xor a
jy_1:   bit 3,c
        jr nz,jy_2
        add a,SHIP_VX
        cp SHIP_XMAX+1
        jr c,jy_2
        ld a,SHIP_XMAX
jy_2:   ld (v_sx),a
        ld a,(v_sy)
        bit 1,c
        jr nz,jy_3
        sub SHIP_VY
        cp SHIP_YMIN
        jr nc,jy_3
        ld a,SHIP_YMIN
jy_3:   bit 2,c
        jr nz,jy_4
        add a,SHIP_VY
        cp SHIP_YMAX+1
        jr c,jy_4
        ld a,SHIP_YMAX
jy_4:   ld (v_sy),a
        ret

; ship_anim: Flammenbild 0,0,1,1,2,2
ship_anim:
        ld a,(v_anim)
        inc a
        cp 6
        jr c,sa_1
        xor a
sa_1:   ld (v_anim),a
        srl a
        ld (v_fl),a
        ret

; row_addr: A = Pixelzeile, C = Zellspalte -> HL = Adresse im Zeichenpuffer; zerstoert A,B
row_addr:
        ld h,PG_LO
        ld l,a
        ld a,(hl)
        or c
        ld b,a
        ld a,(v_hipg)
        ld h,a
        ld a,(hl)
        ld h,a
        ld l,b
        ret

; attr_row_addr: A = Zellzeile, (v_xc) = Spalte -> HL = Attributadresse im Zeichenpuffer
attr_row_addr:
        ld l,a
        ld h,0
        add hl,hl
        add hl,hl
        add hl,hl
        add hl,hl
