        call attr_row_addr
        ld a,(v_gn)
        ld e,a
        ld a,c
        or a
        jr nz,sa_f
        push hl
        ld l,b
        ld h,ROWATTR_PG
        ld a,(hl)
        pop hl
sa_f:   ld (hl),a
        inc l
        dec e
        jr nz,sa_f
        inc b
        dec d
        jr nz,sa_row
        ret

