def block(label, comment, attrs, art):
    assert len(art) == 16, (label, len(art))
    assert len(attrs) == 4
    out = [f"{label}:  ; {comment}"]
    out.append("        db      " + ",".join(f"0{a:02X}h" for a in attrs))
    for row in art:
        assert len(row) == 16, (label, row, len(row))
        assert set(row) <= {"#", "."}, (label, row)
        b = ["".join("1" if c == "#" else "0" for c in row[i:i + 8]) for i in (0, 8)]
        out.append(f"        db      %{b[0]},%{b[1]}   ; {row}")
    return "\n".join(out)


def main(src, dst):
    text = open(src, encoding="utf-8").read()
    tiles = "\n\n".join(block(*b) for b in BLOCKS)
    assert ";@@TILES@@" in text
    open(dst, "w", encoding="utf-8").write(text.replace(";@@TILES@@", tiles))


